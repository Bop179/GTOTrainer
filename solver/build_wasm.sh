#!/bin/bash
# Rebuild river_wasm.js (the browser river solver) from solver/src/lib.rs. Compiles on the VM (the Mac's Homebrew Rust
# has no wasm target). Run from the repo root on the Mac: bash solver/build_wasm.sh
set -e
rsync -az --exclude target --exclude jobs solver/ gto-vm:~/solver/
ssh gto-vm 'cd ~/solver && nice -n 19 ~/.cargo/bin/cargo build --release --lib --no-default-features --target wasm32-unknown-unknown'
W=$(mktemp); trap "rm -f $W" EXIT
scp -q gto-vm:solver/target/wasm32-unknown-unknown/release/gto_solve.wasm "$W"
printf '// Generated by solver/build_wasm.sh: postflop-solver (AGPL-3.0) river solver as base64 WebAssembly. Do not edit.\nwindow.RIVER_WASM="%s";\n' "$(base64 < "$W" | tr -d '\n')" > river_wasm.js
ls -la river_wasm.js
